//! Watching a pull request for a thread, after T3 Code's `watch_pull_request`: every two minutes
//! Hub reads the pull request and, when a check fails, all checks pass, someone comments or
//! reviews, or the branch starts to conflict, sends the thread a message about it so its agent
//! picks the work up again. Watching ends when the pull request merges or closes, after too many
//! failed reads, or when the thread or the user stops it.

use std::collections::BTreeMap;
use std::path::Path;
use std::sync::Arc;
use std::time::Duration;

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};
use serde_json::json;

use crate::hub::Hub;
use crate::model::{PullDetail, ThreadId};

const KEY: &str = "github.watches";
/// The pull request Hub last started watching by itself for a thread, so that stopping a watch
/// is not undone at the next look.
const AUTO_KEY: &str = "github.watch_auto";
/// A thread idle for longer than this is not given a watch by itself; its pull request is not what
/// it is working on.
const AUTO_RECENT_MS: i64 = 6 * 60 * 60 * 1000;
const TICK: Duration = Duration::from_secs(120);
/// Reads in a row that failed before Hub gives up.
const MAX_FAILS: u32 = 8;
/// Wakes in a row that only brought comments before Hub stops, so two agents cannot keep
/// answering each other.
const MAX_COMMENT_WAKES: u32 = 10;

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct Watch {
    pub number: u64,
    /// The folder `gh` runs in.
    pub cwd: String,
    /// What was last seen, so only what is new wakes the thread.
    checks: String,
    mergeable: String,
    seen_until: i64,
    fails: u32,
    comment_wakes: u32,
    /// Started by Hub rather than asked for: passing checks are not worth waking the agent for.
    quiet_pass: bool,
}

/// Lines the agents add to what they post; their own comments do not wake anyone.
fn by_an_agent(body: &str) -> bool {
    ["Generated by [Claude Code]", "Generated with [Claude Code]", "Generated by Claude Code", "Sent from Hub"].iter().any(|m| body.contains(m))
}

/// What changed since `w` was last looked at, as the message for the thread, and `w` updated.
pub fn news(w: &mut Watch, d: &PullDetail) -> Option<String> {
    let first = w.checks.is_empty() && w.seen_until == 0;
    let mut parts = Vec::new();
    let mut only_comments = true;
    let checks = d.pull.checks.clone();
    if !first && checks != w.checks {
        let failed: Vec<&str> = d.checks.iter().filter(|c| c.state == "fail").map(|c| c.name.as_str()).collect();
        match checks.as_str() {
            "fail" => parts.push(format!("A check failed: {}.", failed.join(", "))),
            "pass" if !w.quiet_pass => parts.push("All checks pass.".to_owned()),
            _ => {}
        }
        if matches!(checks.as_str(), "fail" | "pass") {
            only_comments = false;
        }
    }
    if !first && d.pull.mergeable == "conflicts" && w.mergeable != "conflicts" {
        parts.push(format!("The branch now conflicts with {}.", d.pull.base));
        only_comments = false;
    }
    let new: Vec<_> = d.comments.iter().filter(|c| c.at > w.seen_until && !by_an_agent(&c.body)).collect();
    if !first && !new.is_empty() {
        let mut said = String::from("New on the pull request:");
        for c in &new {
            let what = match (c.kind.as_str(), c.verdict.as_deref()) {
                ("review", Some("approved")) => "approved".to_owned(),
                ("review", Some("changes_requested")) => "asked for changes".to_owned(),
                ("line", _) => format!("commented on {}{}", c.path.as_deref().unwrap_or("a file"), c.line.map(|l| format!(":{l}")).unwrap_or_default()),
                _ => "commented".to_owned(),
            };
            let body: String = c.body.trim().chars().take(1500).collect();
            said.push_str(&format!("\n\n{} {what}:\n{}", c.author, if body.is_empty() { "(no text)".into() } else { body }));
        }
        parts.push(said);
    }
    w.checks = checks;
    w.mergeable = d.pull.mergeable.clone();
    w.seen_until = d.comments.iter().map(|c| c.at).max().unwrap_or(0).max(w.seen_until);
    w.fails = 0;
    if parts.is_empty() {
        return None;
    }
    w.comment_wakes = if only_comments { w.comment_wakes + 1 } else { 0 };
    Some(format!(
        "Hub is watching pull request #{} ({}) for you.\n\n{}\n\nTake it from here. Call stop_watching_pull_request when you hand the work back.",
        d.pull.number,
        d.pull.url,
        parts.join("\n\n")
    ))
}

impl Hub {
    pub async fn watches(&self) -> Result<BTreeMap<ThreadId, Watch>> {
        Ok(match self.store.get_value(KEY).await? {
            Some(json) => serde_json::from_str(&json).unwrap_or_default(),
            None => BTreeMap::new(),
        })
    }

    async fn save_watches(&self, w: &BTreeMap<ThreadId, Watch>) -> Result<()> {
        self.store.set_value(KEY, &serde_json::to_string(w)?).await
    }

    /// Starts watching `number`, or the pull request of the thread's branch when it is none.
    /// Returns the number watched.
    pub async fn watch_pr(&self, thread_id: &str, number: Option<u64>) -> Result<u64> {
        self.watch_pr_as(thread_id, number, false).await
    }

    async fn watch_pr_as(&self, thread_id: &str, number: Option<u64>, quiet_pass: bool) -> Result<u64> {
        let thread = self.store.thread(thread_id).await?.context("no such thread")?;
        if thread.host.is_some() {
            bail!("watch it from the machine the thread runs on");
        }
        let number = match number {
            Some(n) => n,
            None => self.thread_prs().get(thread_id).map(|p| p.number as u64).context("this thread's branch has no pull request yet; pass its number")?,
        };
        let mut w = Watch { number, cwd: thread.cwd.clone(), quiet_pass, ..Default::default() };
        // The first read is what is already there; only what comes after wakes the thread.
        let d = crate::github::pull(Path::new(&thread.cwd), number).await?;
        if d.pull.state != "open" {
            bail!("pull request #{number} is {}", d.pull.state);
        }
        news(&mut w, &d);
        let mut all = self.watches().await?;
        all.insert(thread_id.to_owned(), w);
        self.save_watches(&all).await?;
        Ok(number)
    }

    pub async fn unwatch_pr(&self, thread_id: &str) -> Result<bool> {
        let mut all = self.watches().await?;
        let had = all.remove(thread_id).is_some();
        if had {
            self.save_watches(&all).await?;
        }
        Ok(had)
    }

    /// Starts watching the open pull request of each thread that works on one and is not watched
    /// yet, once for each pull request, so that a Stop stays. Hub does it the way the agent could
    /// (`watch_pull_request`), but says nothing when the checks pass.
    pub(crate) async fn auto_watch(&self, threads: &[crate::model::Thread]) -> Result<()> {
        let prs = self.thread_prs();
        let watched = self.watches().await?;
        let mut tried: BTreeMap<ThreadId, u64> = match self.store.get_value(AUTO_KEY).await? {
            Some(json) => serde_json::from_str(&json).unwrap_or_default(),
            None => BTreeMap::new(),
        };
        let recent = crate::model::now_ms() - AUTO_RECENT_MS;
        let mut changed = false;
        for t in threads {
            if t.host.is_some() || t.archived || t.settled_at.is_some() || t.updated_at < recent {
                continue;
            }
            let Some(pr) = prs.get(&t.id).filter(|pr| matches!(pr.state.as_str(), "open" | "draft")) else { continue };
            let number = u64::from(pr.number);
            if watched.contains_key(&t.id) || tried.get(&t.id) == Some(&number) {
                continue;
            }
            tried.insert(t.id.clone(), number);
            changed = true;
            match self.watch_pr_as(&t.id, Some(number), true).await {
                Ok(_) => tracing::info!(thread = %t.id, "watching pull request #{number} for the thread"),
                Err(err) => tracing::info!(thread = %t.id, "not watching pull request #{number}: {err:#}"),
            }
        }
        if changed {
            self.store.set_value(AUTO_KEY, &serde_json::to_string(&tried)?).await?;
        }
        Ok(())
    }

    /// Reads every watched pull request every two minutes.
    pub(crate) async fn watch_prs(self: Arc<Self>) {
        loop {
            tokio::time::sleep(TICK).await;
            if let Err(err) = self.watch_once().await {
                tracing::warn!("watching pull requests: {err:#}");
            }
        }
    }

    async fn watch_once(self: &Arc<Self>) -> Result<()> {
        let all = self.watches().await?;
        if all.is_empty() {
            return Ok(());
        }
        // Each watch either goes on, updated, or ends (None).
        let mut after: BTreeMap<ThreadId, (u64, Option<Watch>)> = BTreeMap::new();
        for (id, mut w) in all {
            let number = w.number;
            let Some(thread) = self.store.thread(&id).await? else {
                after.insert(id, (number, None));
                continue;
            };
            // Settling or archiving a thread ends its watch.
            if thread.archived || thread.settled_at.is_some() {
                after.insert(id, (number, None));
                continue;
            }
            let d = match crate::github::pull(Path::new(&w.cwd), number).await {
                Ok(d) => d,
                Err(err) => {
                    w.fails += 1;
                    tracing::info!(thread = %id, "reading pull request #{number}: {err:#}");
                    after.insert(id, (number, (w.fails < MAX_FAILS).then_some(w)));
                    continue;
                }
            };
            if d.pull.state != "open" {
                after.insert(id, (number, None));
                continue;
            }
            if let Some(text) = news(&mut w, &d) {
                let mark = json!({ "number": number });
                if let Err(err) = self.send_from(&id, text, Vec::new(), None, Some(("watch", mark)), None).await {
                    tracing::warn!(thread = %id, "waking for pull request #{number}: {err:#}");
                }
            }
            after.insert(id, (number, (w.comment_wakes < MAX_COMMENT_WAKES).then_some(w)));
        }
        // A watch started or stopped while this ran wins over what this read.
        let mut now = self.watches().await?;
        for (id, (number, w)) in after {
            if now.get(&id).is_none_or(|slot| slot.number != number) {
                continue;
            }
            match w {
                Some(w) => now.insert(id, w),
                None => now.remove(&id),
            };
        }
        self.save_watches(&now).await
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{PullCheck, PullComment, PullRow};

    fn pr(checks: &str, mergeable: &str, comments: Vec<PullComment>) -> PullDetail {
        PullDetail {
            pull: PullRow { number: 7, url: "u".into(), checks: checks.into(), mergeable: mergeable.into(), base: "main".into(), ..Default::default() },
            body: String::new(),
            created_at: 0,
            merged_at: None,
            checks: vec![PullCheck { name: "test".into(), state: if checks == "fail" { "fail".into() } else { "pass".into() }, url: None }],
            comments,
            commits: vec![],
            files: vec![],
            reviewers: vec![],
            auto_merge: false,
            merge_state: String::new(),
            methods: vec![],
            deletes_branch: false,
        }
    }

    fn said(at: i64, body: &str) -> PullComment {
        PullComment { kind: "comment".into(), author: "me".into(), body: body.into(), at, url: None, verdict: None, path: None, line: None }
    }

    #[test]
    fn wakes_only_on_what_is_new() {
        let mut w = Watch::default();
        // What is there when watching starts is not news.
        assert!(news(&mut w, &pr("pending", "yes", vec![said(1, "old")])).is_none());
        assert!(news(&mut w, &pr("pending", "yes", vec![said(1, "old")])).is_none());
        let fail = news(&mut w, &pr("fail", "yes", vec![said(1, "old")])).unwrap();
        assert!(fail.contains("A check failed: test.") && !fail.contains("old"));
        let both = news(&mut w, &pr("fail", "conflicts", vec![said(1, "old"), said(5, "Rename it please")])).unwrap();
        assert!(both.contains("conflicts with main") && both.contains("Rename it please") && !both.contains("check failed"));
        assert!(news(&mut w, &pr("pass", "conflicts", vec![])).unwrap().contains("All checks pass."));
    }

    #[test]
    fn a_watch_hub_started_stays_quiet_when_checks_pass() {
        let mut w = Watch { quiet_pass: true, ..Default::default() };
        assert!(news(&mut w, &pr("pending", "yes", vec![])).is_none());
        assert!(news(&mut w, &pr("pass", "yes", vec![])).is_none());
        assert!(news(&mut w, &pr("fail", "yes", vec![])).unwrap().contains("A check failed"));
        assert!(news(&mut w, &pr("pass", "yes", vec![said(5, "Rename it")])).unwrap().contains("Rename it"));
    }

    #[test]
    fn agents_do_not_wake_themselves() {
        let mut w = Watch::default();
        news(&mut w, &pr("pass", "yes", vec![]));
        let agent = said(9, "Fixed.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_");
        assert!(news(&mut w, &pr("pass", "yes", vec![agent])).is_none());
        for i in 0..3 {
            news(&mut w, &pr("pass", "yes", vec![said(20 + i, "again")])).unwrap();
        }
        assert_eq!(w.comment_wakes, 3);
    }
}
